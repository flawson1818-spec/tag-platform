let cached: Uint8Array | null = null;

function bits(): Uint8Array {
  if (cached) return cached;
  const raw = atob(LAND_MASK_BASE64);
  const out = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i++) out[i] = raw.charCodeAt(i);
  cached = out;
  return out;
}

/** Centre (lat, lon) of every land cell. */
export function landCellCentres(): { lat: number; lon: number }[] {
  const mask = bits();
  const cells: { lat: number; lon: number }[] = [];
  for (let r = 0; r < LAND_MASK_ROWS; r++) {
    for (let c = 0; c < LAND_MASK_COLS; c++) {
      const i = r * LAND_MASK_COLS + c;
      if (mask[i >> 3] & (1 << (i & 7))) {
        cells.push({ lat: 90 - (r + 0.5) * LAND_MASK_STEP_DEG, lon: -180 + (c + 0.5) * LAND_MASK_STEP_DEG });
      }
    }
  }
  return cells;
}

export function isLand(lat: number, lon: number): boolean {
  const r = Math.min(LAND_MASK_ROWS - 1, Math.max(0, Math.floor((90 - lat) / LAND_MASK_STEP_DEG)));
  const c = Math.min(LAND_MASK_COLS - 1, Math.max(0, Math.floor((((lon + 180) % 360) + 360) % 360 / LAND_MASK_STEP_DEG)));
  const i = r * LAND_MASK_COLS + c;
  return Boolean(bits()[i >> 3] & (1 << (i & 7)));
}
